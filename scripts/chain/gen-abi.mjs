#!/usr/bin/env node
// gen-abi.mjs — writes src/chain/abi.generated.ts from the Foundry build output.
// Usage: node scripts/chain/gen-abi.mjs [--no-build]
// Runs `forge build` in contracts/ (pinned local binary) unless --no-build, then reads
// contracts/out/<Contract>.sol/<Contract>.json `abi` arrays. No addresses are written here.
// Exit codes: 0 ok, 1 build/read/write failure.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, renameSync, statSync, unlinkSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '..', '..');
const CONTRACTS = join(ROOT, 'contracts');
const FORGE = join(CONTRACTS, '.tools', 'bin', 'forge');
const OUT_FILE = join(ROOT, 'src', 'chain', 'abi.generated.ts');
// Foundry cache is kept outside the project, inside the permitted location.
const FOUNDRY_CACHE = join(homedir(), '.foundry', 'cache', 'nobodyfirst-stage3');

const EXPORTS = [
  { name: 'coordinatorAbi', artifact: 'AtomicCoordinator.sol/AtomicCoordinator.json' },
  { name: 'itemsAbi', artifact: 'GameItems.sol/GameItems.json' },
  { name: 'npcAbi', artifact: 'NPC_A.sol/NPC_A.json' },
  { name: 'deployerAbi', artifact: 'Level1Deployer.sol/Level1Deployer.json' },
];

const forgeEnv = () => ({ ...process.env, FOUNDRY_CACHE_PATH: FOUNDRY_CACHE });
const die = (msg, extra = {}) => {
  console.error(`gen-abi: ${msg}`);
  console.log(JSON.stringify({ ok: false, command: 'gen-abi', error: msg, ...extra }));
  process.exit(1);
};

// Recursively sorts object keys so output and hashes do not depend on key insertion order.
const canonical = (v) => {
  if (Array.isArray(v)) return v.map(canonical);
  if (v && typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).sort()) out[k] = canonical(v[k]);
    return out;
  }
  return v;
};

const args = new Set(process.argv.slice(2));
const unknown = [...args].filter((a) => a !== '--no-build');
if (unknown.length) die(`unknown argument(s): ${unknown.join(' ')}`);

let forgeVersion;
try {
  const v = execFileSync(FORGE, ['--version'], { encoding: 'utf8', env: forgeEnv() });
  forgeVersion = /Version:\s*(\S+)/.exec(v)?.[1] ?? 'unknown';
} catch (e) {
  die(`forge not runnable at ${FORGE}: ${e.message.split('\n')[0]}`);
}

if (!args.has('--no-build')) {
  try {
    execFileSync(FORGE, ['build'], { cwd: CONTRACTS, env: forgeEnv(), encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    die('forge build failed', { stderr: String(e.stderr ?? '').split('\n').slice(-20).join('\n') });
  }
}

const sections = [];
const headerLines = [];
let newestMtime = 0;
for (const { name, artifact } of EXPORTS) {
  const path = join(CONTRACTS, 'out', artifact);
  let json;
  try {
    json = JSON.parse(readFileSync(path, 'utf8'));
    newestMtime = Math.max(newestMtime, statSync(path).mtimeMs);
  } catch (e) {
    die(`cannot read ${artifact}: ${e.code ?? e.message}`);
  }
  if (!Array.isArray(json.abi) || json.abi.length === 0) die(`${artifact} has no abi`);
  const abi = canonical(json.abi);
  const digest = createHash('sha256').update(JSON.stringify(abi)).digest('hex');
  const errors = abi.filter((e) => e.type === 'error').length;
  headerLines.push(`//   ${name}: out/${artifact} (${abi.length} entries, ${errors} errors) sha256=${digest}`);
  const body = abi.map((entry) => `  ${JSON.stringify(entry)},`).join('\n');
  sections.push(`export const ${name} = [\n${body}\n] as const;\n`);
}

const builtAt = newestMtime ? new Date(newestMtime).toISOString() : 'unknown';
const text = [
  '// AUTO-GENERATED by scripts/chain/gen-abi.mjs. Do not edit by hand.',
  `// Source: contracts/out (forge build), forge ${forgeVersion}, artifacts last built ${builtAt}.`,
  '// sha256 = SHA-256 of the canonical (key-sorted) JSON of each ABI array.',
  ...headerLines,
  '// Contains no addresses. Deployment data lives in contracts/deployments/local-anvil.json.',
  '',
  ...sections,
].join('\n');

const tmp = `${OUT_FILE}.tmp-${process.pid}`;
try {
  writeFileSync(tmp, text, 'utf8');
  renameSync(tmp, OUT_FILE);
} catch (e) {
  try { unlinkSync(tmp); } catch {}
  die(`cannot write ${OUT_FILE}: ${e.message}`);
}

console.log(
  JSON.stringify({
    ok: true,
    command: 'gen-abi',
    output: 'src/chain/abi.generated.ts',
    forgeVersion,
    built: !args.has('--no-build'),
    exports: EXPORTS.map(({ name, artifact }) => ({ name, artifact })),
  }),
);
